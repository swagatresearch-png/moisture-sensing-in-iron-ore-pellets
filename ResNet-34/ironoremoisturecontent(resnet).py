import time
import torch
import cv2
import numpy as np
from PIL import Image
from torchvision import transforms

def benchmark_inference(iterations=100):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[INFO] Initializing benchmark on: {device.type.upper()}")

    if not os.path.exists('best.pt'):
        print("[ERROR] 'best.pt' not found! Cannot run benchmark.")
        return

    # 1. Load Model
    model = DualStreamFusionNet(num_classes=len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best.pt', map_location=device, weights_only=True))
    model.eval()

    # 2. Setup standard pipeline transforms
    transform = transforms.Compose([
        transforms.Resize((224, 224)),
        transforms.ToTensor(),
        transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ])

    # 3. Create a standardized synthetic image (simulates a camera frame)
    dummy_image = Image.fromarray(np.random.randint(0, 255, (300, 300, 3), dtype=np.uint8))

    # ---------------------------------------------------------
    # HARDWARE WARMUP (Critical for accurate GPU timing)
    # ---------------------------------------------------------
    print("[INFO] Warming up hardware architecture (10 passes)...")
    for _ in range(10):
        i_tensor = transform(dummy_image).unsqueeze(0).to(device)
        i_cv = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
        m_tensor = torch.tensor(compute_mlbp(i_cv), dtype=torch.float32).unsqueeze(0).to(device)
        with torch.no_grad():
            _ = model(i_tensor, m_tensor)

    print(f"[INFO] Hardware warm-up complete. Benchmarking {iterations} iterations...\n")

    # ---------------------------------------------------------
    # TEST 1: PURE NEURAL NETWORK INFERENCE (GPU Bound)
    # ---------------------------------------------------------
    # Pre-calculate data so we ONLY time the neural network
    img_tensor = transform(dummy_image).unsqueeze(0).to(device)
    img_cv = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
    mlbp_tensor = torch.tensor(compute_mlbp(img_cv), dtype=torch.float32).unsqueeze(0).to(device)

    model_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()

            _ = model(img_tensor, mlbp_tensor)

            if device.type == 'cuda': torch.cuda.synchronize()
            t_end = time.perf_counter()
            model_times.append((t_end - t_start) * 1000) # Convert to milliseconds

    avg_model_time = np.mean(model_times)

    # ---------------------------------------------------------
    # TEST 2: FULL END-TO-END PIPELINE (CPU + GPU Bound)
    # ---------------------------------------------------------
    pipeline_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()

            # Step A: Data Preprocessing & Local Branch (MLBP Math on CPU)
            i_tensor = transform(dummy_image).unsqueeze(0).to(device)
            i_cv = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
            m_tensor = torch.tensor(compute_mlbp(i_cv), dtype=torch.float32).unsqueeze(0).to(device)

            # Step B: Global Branch & Fusion (AI Model on GPU)
            _ = model(i_tensor, m_tensor)

            if device.type == 'cuda': torch.cuda.synchronize()
            t_end = time.perf_counter()
            pipeline_times.append((t_end - t_start) * 1000)

    avg_pipe_time = np.mean(pipeline_times)

    # ---------------------------------------------------------
    # REPORT GENERATION
    # ---------------------------------------------------------
    print("="*60)
    print("                 INFERENCE SPEED REPORT")
    print("="*60)
    print(f"1. Pure AI Model Latency : {avg_model_time:.2f} ms / frame")
    print(f"   Max Theoretical Speed : {1000/avg_model_time:.1f} FPS")
    print("-" * 60)
    print(f"2. Full Pipeline Latency : {avg_pipe_time:.2f} ms / frame")
    print("   (Includes Image Prep + MLBP Math + AI Forward Pass)")
    print(f"   Actual Production FPS : {1000/avg_pipe_time:.1f} FPS")
    print("="*60)
    print("* Note: FPS >= 30 is generally considered real-time for conveyor belt cameras.")

# Execute Benchmark
benchmark_inference()