def compute_mlbp(image_cv_gray):
    """
    Computes Modified Local Binary Pattern (MLBP) over an 8-equidistant neighborhood.
    Preserves structural features against specular highlights by using 3x3 block mean as threshold (tau).
    Output: 256-D normalized histogram vector.
    """
    h, w = image_cv_gray.shape
    img_float = image_cv_gray.astype(np.float32)

    # Compute threshold tau (mean of 3x3 neighborhood) using convolution
    kernel = np.ones((3, 3), np.float32) / 9.0
    mean_tau = cv2.filter2D(img_float, -1, kernel)

    # Pad image for P=8, R=1 neighbors
    padded = np.pad(img_float, 1, mode='reflect')
    mlbp = np.zeros((h, w), dtype=np.uint8)

    # 8 neighbors defined by offsets
    dx = [-1,  0,  1, 1, 1, 0, -1, -1]
    dy = [-1, -1, -1, 0, 1, 1,  1,  0]

    for i in range(8):
        y1, y2 = 1 + dy[i], 1 + dy[i] + h
        x1, x2 = 1 + dx[i], 1 + dx[i] + w
        neighbor = padded[y1:y2, x1:x2]

        # Step activation: s(x_p - tau)
        bit = (neighbor >= mean_tau).astype(np.uint8)
        mlbp |= (bit << i)

    hist, _ = np.histogram(mlbp.ravel(), bins=256, range=(0, 256))
    hist = hist.astype(np.float32)
    return hist / (hist.sum() + 1e-6) # L1 Normalization

class PelletDataset(Dataset):
    def __init__(self, root_dir, transform=None):
        self.root_dir = Path(root_dir)
        self.transform = transform
        self.image_paths = []
        self.labels = []

        # Accept all standard image formats, ignoring uppercase/lowercase differences
        valid_extensions = ('.jpg', '.jpeg', '.png', '.bmp', '.tiff', '.tif', '.webp')

        for idx, cls in enumerate(CLASSES):
            cls_dir = self.root_dir / cls
            if cls_dir.exists():
                for file_name in os.listdir(cls_dir):
                    if file_name.lower().endswith(valid_extensions):
                        self.image_paths.append(str(cls_dir / file_name))
                        self.labels.append(idx)

        if len(self.image_paths) == 0:
            raise ValueError(f"No images found in {root_dir}. Check file formats.")

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_path = self.image_paths[idx]
        image_pil = Image.open(img_path).convert('RGB')
        label = self.labels[idx]

        # Global Branch Tensor
        img_tensor = self.transform(image_pil) if self.transform else transforms.ToTensor()(image_pil)

        # MLBP Local Branch Vector
        img_cv_gray = cv2.cvtColor(np.array(image_pil), cv2.COLOR_RGB2GRAY)
        img_cv_gray = cv2.resize(img_cv_gray, (224, 224))
        mlbp_vec = compute_mlbp(img_cv_gray)
        mlbp_tensor = torch.tensor(mlbp_vec, dtype=torch.float32)

        return img_tensor, mlbp_tensor, label

class ChannelAttention(nn.Module):
    def __init__(self, in_planes, ratio=16):
        super().__init__()
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.max_pool = nn.AdaptiveMaxPool2d(1)
        self.mlp = nn.Sequential(
            nn.Conv2d(in_planes, in_planes // ratio, 1, bias=False),
            nn.ReLU(),
            nn.Conv2d(in_planes // ratio, in_planes, 1, bias=False)
        )
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        avg_out = self.mlp(self.avg_pool(x))
        max_out = self.mlp(self.max_pool(x))
        return self.sigmoid(avg_out + max_out)

class SpatialAttention(nn.Module):
    def __init__(self, kernel_size=7):
        super().__init__()
        self.conv = nn.Conv2d(2, 1, kernel_size, padding=kernel_size//2, bias=False)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x):
        avg_out = torch.mean(x, dim=1, keepdim=True)
        max_out, _ = torch.max(x, dim=1, keepdim=True)
        x_cat = torch.cat([avg_out, max_out], dim=1)
        return self.sigmoid(self.conv(x_cat))

class CBAM(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.ca = ChannelAttention(channels)
        self.sa = SpatialAttention()

    def forward(self, x):
        x = self.ca(x) * x
        x = self.sa(x) * x
        return x

class DualStreamFusionNet(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()
        # Backbone (ResNet34 truncated at layer4 -> 512 channels)
        resnet = models.resnet34(weights=models.ResNet34_Weights.IMAGENET1K_V1)
        self.features = nn.Sequential(
            resnet.conv1, resnet.bn1, resnet.relu, resnet.maxpool,
            resnet.layer1, resnet.layer2, resnet.layer3, resnet.layer4
        )
        # Attention
        self.cbam = CBAM(512)
        self.global_pool = nn.AdaptiveAvgPool2d(1)

        # Fusion Classifier (512 Global + 256 Local Texture)
        self.classifier = nn.Sequential(
            nn.Linear(512 + 256, 512),
            nn.BatchNorm1d(512),
            nn.ReLU(),
            nn.Dropout(0.4),
            nn.Linear(512, num_classes)
        )

    def forward(self, img, mlbp):
        # Stream B: Global Branch
        f_global = self.features(img)
        f_global = self.cbam(f_global)
        f_global = self.global_pool(f_global)
        f_global = torch.flatten(f_global, 1) # [B, 512]

        # Multimodal Fusion
        f_fused = torch.cat([f_global, mlbp], dim=1) # [B, 768]

        # Projection
        out = self.classifier(f_fused)
        return out

